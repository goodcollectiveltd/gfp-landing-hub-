"""Pre-render the countdown artwork for netlify/functions/countdown/countdown.mjs.

Everything in the timer is a mix of two colours, white and brand navy, so each
pixel is stored as a 0..15 coverage level (0 = white, 15 = navy). The function
only has to drop digit masks into fixed slots and write a 16-colour GIF, which
keeps it dependency-free and fast.

Run:  python scripts/countdown/build-glyphs.py
Out:  netlify/functions/countdown/art.mjs
"""
import base64, json, os, zlib
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONTS = os.path.join(ROOT, "..", "company-context", "brand-assets", "fonts")
POPPINS = os.path.join(FONTS, "Poppins-Bold.ttf")
INTER = os.path.join(FONTS, "Inter-Bold.ttf")

S = 2                         # draw at 2x, displayed at 600 wide
W, H = 600 * S, 128 * S
BOX_W, BOX_H, GAP, RAD = 120 * S, 82 * S, 16 * S, 12 * S
TOP = 4 * S
LEFT = (W - (4 * BOX_W + 3 * GAP)) // 2
DIGIT_PX = 52 * S
LABEL_PX = 19 * S
LABELS = ["DAYS", "HOURS", "MINS", "SECS"]
SS = 4                        # supersample for smooth edges


def coverage(img_l):
    """L-mode 0..255 coverage -> list of 0..15 levels."""
    return [round(v * 15 / 255) for v in img_l.get_flattened_data()]


def pack(levels):
    return base64.b64encode(zlib.compress(bytes(levels), 9)).decode()


# ---- base: four navy rounded boxes and their labels, on white ----
big = Image.new("L", (W * SS, H * SS), 0)
d = ImageDraw.Draw(big)
for i in range(4):
    x = (LEFT + i * (BOX_W + GAP)) * SS
    d.rounded_rectangle([x, TOP * SS, x + BOX_W * SS - 1, (TOP + BOX_H) * SS - 1], radius=RAD * SS, fill=255)
lab_font = ImageFont.truetype(INTER, LABEL_PX * SS)
for i, lab in enumerate(LABELS):
    cx = (LEFT + i * (BOX_W + GAP) + BOX_W // 2) * SS
    tracking = 2.0 * S * SS
    widths = [lab_font.getlength(c) for c in lab]
    total = sum(widths) + tracking * (len(lab) - 1)
    x = cx - total / 2
    y = (TOP + BOX_H + 9 * S) * SS
    for c, w in zip(lab, widths):
        d.text((x, y), c, font=lab_font, fill=255)
        x += w + tracking
base = big.resize((W, H), Image.LANCZOS)
base_levels = coverage(base)

# ---- digit masks: every digit centred in one fixed-width slot ----
dig_font = ImageFont.truetype(POPPINS, DIGIT_PX * SS)
adv = max(dig_font.getlength(str(n)) for n in range(10))
SLOT_W = int(adv / SS) + 2 * S
SLOT_H = int(DIGIT_PX * 1.0)
digits = {}
for n in range(10):
    g = Image.new("L", (SLOT_W * SS, SLOT_H * SS), 0)
    gd = ImageDraw.Draw(g)
    bb = gd.textbbox((0, 0), str(n), font=dig_font)
    gw, gh = bb[2] - bb[0], bb[3] - bb[1]
    cap = gd.textbbox((0, 0), "0", font=dig_font)
    capH = cap[3] - cap[1]
    gx = (SLOT_W * SS - gw) / 2 - bb[0]
    gy = (SLOT_H * SS - capH) / 2 - cap[1]
    gd.text((gx, gy), str(n), font=dig_font, fill=255)
    digits[str(n)] = pack(coverage(g.resize((SLOT_W, SLOT_H), Image.LANCZOS)))

# ---- where the eight digits go: two per box, centred ----
slots = []
for i in range(4):
    bx = LEFT + i * (BOX_W + GAP)
    pair_w = 2 * SLOT_W
    x0 = bx + (BOX_W - pair_w) // 2
    y0 = TOP + (BOX_H - SLOT_H) // 2
    slots += [[x0, y0], [x0 + SLOT_W, y0]]

art = {"w": W, "h": H, "slotW": SLOT_W, "slotH": SLOT_H, "slots": slots,
       "base": pack(base_levels), "digits": digits}
out = os.path.join(ROOT, "netlify", "functions", "countdown", "art.mjs")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/countdown/build-glyphs.py. Do not edit by hand.\n")
    f.write("export default " + json.dumps(art) + ";\n")
print("wrote", out, os.path.getsize(out) // 1024, "KB", f"{W}x{H}", "slot", SLOT_W, SLOT_H)
